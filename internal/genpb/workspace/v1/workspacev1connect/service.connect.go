// WorkspaceCatalogServiceHandler is an implementation of the
// daft.workspace.v1.WorkspaceCatalogService service.
type WorkspaceCatalogServiceHandler interface {
	// Create mints a new Workspace owned by the calling identity.
	// The orchestrator assigns the UUID; the caller supplies the
	// human-readable name (defaults applied client-side from
	// basename($PWD), but server-side requires a non-empty name).
	Create(context.Context, *connect.Request[v1.CreateWorkspaceRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// Get returns the Workspace addressed by handle. Used by the
	// CLI's `daft workspace status` (which renders the Missing[]
	// list for the user).
	Get(context.Context, *connect.Request[v1.GetWorkspaceRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// List returns every workspace in the catalog. mine_only=true
	// filters to those owned by the calling identity. List is
	// read-only; persistence (Slice B5) will reuse the same shape.
	List(context.Context, *connect.Request[v1.ListWorkspacesRequest]) (*connect.Response[v1.ListWorkspacesResponse], error)
	// Apply atomically creates or replaces the complete declared WorkspaceSpec.
	// A name handle with expected_generation=0 creates when absent; positive
	// generations update an existing name or UUID. An identical retry is a
	// no-op even when its generation is stale.
	Apply(context.Context, *connect.Request[v1.ApplyWorkspaceRequest]) (*connect.Response[v1.ApplyWorkspaceResponse], error)
	// SetImage records an OCI image reference. Replaces any prior
	// image_ref or pending_build_id. Empty image_ref clears the
	// field (reverts to DRAFT if no other image source set).
	SetImage(context.Context, *connect.Request[v1.SetImageRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// SetDevcontainer records the path to a devcontainer.json within the
	// workspace content. At Launch the orchestrator reads it from the
	// pushed content, projects it to a base spec, and overlays the
	// explicit spec fields on top. Empty clears it.
	SetDevcontainer(context.Context, *connect.Request[v1.SetDevcontainerRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// SetTarget pins the workspace to a specific sandbox-host by
	// mTLS fingerprint. Empty fingerprint clears the pin (scheduler
	// will pick at Launch time, once Launch lands in B2c).
	SetTarget(context.Context, *connect.Request[v1.SetTargetRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// SetResources records the guest VM's RAM and vCPU sizing.
	// Zero in either field clears it (reverts to the executor's
	// default). Projected onto the SandboxSpec at Launch.
	SetResources(context.Context, *connect.Request[v1.SetResourcesRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// SetNestedVirtualization toggles whether the workload may run
	// its own (L2) VMs — when enabled the executor binds /dev/kvm
	// into the container and adds the cgroup device-allow. Off by
	// default (a privilege/attack-surface bump). Projected onto the
	// SandboxSpec at Launch.
	SetNestedVirtualization(context.Context, *connect.Request[v1.SetNestedVirtualizationRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// SetPrivilegedFuseMounts toggles whether the workload may mount
	// FUSE filesystems — when enabled the executor binds /dev/fuse into
	// the container, adds the cgroup device-allow, and grants
	// CAP_SYS_ADMIN (near-root inside the VM). Off by default (a real
	// privilege/attack-surface bump). Projected onto the SandboxSpec at
	// Launch.
	SetPrivilegedFuseMounts(context.Context, *connect.Request[v1.SetPrivilegedFuseMountsRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// SetPrivilegedBuild toggles the build capability grant — when enabled
	// the executor gives the container the standard container cap set so an
	// in-sandbox buildah can build images. Off by default (a privilege
	// bump; see the PrivilegedBuild message). Projected onto the SandboxSpec
	// at Launch.
	SetPrivilegedBuild(context.Context, *connect.Request[v1.SetPrivilegedBuildRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// AddMount appends a Mount to the workspace. Mount.target must
	// be absolute; the orchestrator rejects empty or relative targets
	// and refuses a duplicate target in the existing mount set.
	AddMount(context.Context, *connect.Request[v1.AddMountRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// AddEnv appends an EnvVar. Empty name is rejected. Duplicate
	// names are rejected (use the future B2b RemoveEnv first).
	AddEnv(context.Context, *connect.Request[v1.AddEnvRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// AddPort appends a PortMapping. Container port and protocol
	// must be set explicitly; UNSPECIFIED protocol is rejected so
	// the orchestrator's ingress (Phase C) can shape correctly.
	AddPort(context.Context, *connect.Request[v1.AddPortRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// RemoveMount drops the mount whose target matches the request.
	// Returns NotFound if no mount has that target. Symmetric to
	// AddMount; the per-user-host RemapMount / FlagMount overrides
	// live in WorkspaceAdoptionService (Phase F).
	RemoveMount(context.Context, *connect.Request[v1.RemoveMountRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// RemoveEnv drops the env var with the given name. Returns
	// NotFound if no env has that name.
	RemoveEnv(context.Context, *connect.Request[v1.RemoveEnvRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// RemovePort drops the port mapping with the given (port,
	// protocol). Returns NotFound if the pair is not present.
	RemovePort(context.Context, *connect.Request[v1.RemovePortRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// Validate recomputes the workspace's readiness. DRAFT
	// workspaces with no missing fields auto-promote to READY;
	// READY workspaces whose state has since drifted (e.g. the
	// last mount was removed) auto-demote to DRAFT. Returns the
	// resulting workspace; no transition is treated as an error.
	// RUNNING / FROZEN / STOPPED / ARCHIVED workspaces are left
	// untouched — Validate is the readiness sieve for not-yet-
	// launched workspaces only.
	Validate(context.Context, *connect.Request[v1.ValidateRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// Launch dispatches the workspace to its pinned sandbox-host.
	// Preconditions: status READY or STOPPED; missing[] empty;
	// target_sandbox_fingerprint set. The orchestrator mints a
	// fresh dispatch_id, composes a SandboxSpec from the workspace,
	// and ships it via the sandbox-control stream. On success the
	// status transitions to RUNNING and current_dispatch_id is
	// populated. FailedPrecondition for state-machine violations
	// and offline sandboxes; Unavailable when the sandbox is
	// momentarily backlogged (the caller may retry).
	Launch(context.Context, *connect.Request[v1.LaunchRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// Stop transitions a RUNNING or FROZEN workspace to STOPPED
	// and clears current_dispatch_id. For Slice B2c this is
	// catalog-only — the wire teardown signal to the sandbox-host
	// lands in a follow-up sub-slice. STOPPED workspaces stay
	// mutable; a subsequent Launch boots a fresh VM.
	Stop(context.Context, *connect.Request[v1.StopRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// Delete permanently removes a stopped workspace catalog record. The exact
	// generation guard prevents a stale client deleting a concurrently edited
	// workspace after Node-side data cleanup.
	Delete(context.Context, *connect.Request[v1.DeleteWorkspaceRequest]) (*connect.Response[v1.DeleteWorkspaceResponse], error)
	// Acquire takes (or refreshes) the workspace's per-owner write
	// lock. While the lock is held, only the holder can mutate the
	// workspace; every other authenticated caller's mutator
	// returns FailedPrecondition with reason LockHeld. The lock
	// auto-releases after the requested TTL — Acquire is also the
	// refresh primitive (calling Acquire as the current holder
	// extends the expiry).
	//
	// Refusal cases: held by someone else and not yet expired
	// (FailedPrecondition). Refusal for an unknown workspace
	// surfaces as NotFound. Phase F3 adds an explicit `force`
	// override with an audit-log entry; B2d ships only the
	// own-or-unheld semantic.
	Acquire(context.Context, *connect.Request[v1.AcquireRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// Release clears the workspace's write lock if held by the
	// caller. Calling Release on an unheld workspace is a no-op
	// (idempotent); calling it on a workspace held by someone
	// else returns FailedPrecondition with reason LockHeld.
	Release(context.Context, *connect.Request[v1.ReleaseRequest]) (*connect.Response[v1.WorkspaceResponse], error)
	// ForwardPort is the bidi byte channel a user-host CLI dials
	// to tunnel local TCP traffic into a running workspace's
	// container. The first message MUST be a ForwardFrame{hello}
	// carrying the addressed (workspace, container_port);
	// subsequent messages carry data bytes.
	//
	// The orchestrator resolves the workspace to its bound Node,
	// calls OpenPortBridge to open a labeled stream into the
	// sandboxd, and io.Copy splices the two streams. Errors:
	// NotFound when the handle doesn't resolve; FailedPrecondition
	// when the workspace isn't RUNNING (no current_sandbox);
	// Unavailable when the Node is offline or the stream backlog is
	// full. See PLAN.md Phase C3.
	ForwardPort(context.Context, *connect.BidiStream[v1.ForwardFrame, v1.ForwardFrame]) error
	// AttachSandbox is the bidi PTY channel a user-host CLI dials
	// to open an interactive shell (or arbitrary exec) inside the
	// running workspace's container. The first frame on the
	// client side MUST be an AttachFrame{hello} carrying the
	// workspace handle, the command to exec, and (if tty=true)
	// the initial window size. The orchestrator resolves the
	// workspace, calls OpenAttachBridge to open a sandboxd-side
	// AttachStream, and splices the two bidi streams. Data frames
	// pass through opaquely; resize frames flow client → sandbox
	// and translate to the in-VM PTY's TIOCSWINSZ.
	//
	// Errors: NotFound when the handle doesn't resolve;
	// FailedPrecondition when the workspace isn't RUNNING (no
	// current_sandbox); Unavailable when the Node is offline.
	// See PLAN.md Slice D2.
	AttachSandbox(context.Context, *connect.BidiStream[v1.AttachFrame, v1.AttachFrame]) error
	// ObserverTail streams a running workspace's per-sandbox host-side
	// observer log (the newline-delimited JSON Tier-1 trace) back to a
	// user-host CLI — `daft sandbox observer-tail`. The orchestrator
	// resolves the workspace to its current_sandbox, calls
	// OpenObserverBridge to open a sandboxd-side ObserverStream, and
	// relays the log chunks. Read-only: data flows sandbox → client
	// only. When follow is false the current file is sent once and the
	// stream ends; when true the stream stays open and forwards new
	// lines as the observer appends them (tail -f).
	//
	// Errors: NotFound when the handle doesn't resolve;
	// FailedPrecondition when the workspace isn't RUNNING (no
	// current_sandbox); Unavailable when the Node is offline.
	ObserverTail(context.Context, *connect.Request[v1.ObserverTailRequest], *connect.ServerStream[v1.ObserverChunk]) error
	// ObserveSummary returns the current build-progress summary snapshot
	// for a running workspace's sandbox — the guest-written
	// progress.Summary JSON, surfaced to `daft sandbox observe`. One-shot
	// and unary: the orchestrator resolves the workspace to its
	// current_sandbox, reads the summary file once over the node broker
	// (the same rendezvous as ObserverTail, with the summary source
	// selector), and returns the bytes verbatim. The CLI polls this on an
	// interval for --follow, which is well-defined because the summary
	// file is rewritten atomically.
	//
	// Errors: NotFound when the handle doesn't resolve;
	// FailedPrecondition when the workspace isn't RUNNING (no
	// current_sandbox); Unavailable when the Node is offline.
	ObserveSummary(context.Context, *connect.Request[v1.ObserveSummaryRequest]) (*connect.Response[v1.ObserveSummaryResponse], error)
}

