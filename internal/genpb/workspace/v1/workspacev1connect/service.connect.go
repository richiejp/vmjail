// WorkspaceCatalogService is the orchestrator-facing surface that
// clients (`daft workspace …` from the user-host) use to
// incrementally assemble a Workspace. The catalog itself lives in
// internal/workspacecatalog (Slice B1); this service is the wire
// adapter (Slice B2).
//
// Naming: the existing daft.workspace.v1.WorkspaceService is the
// chunk/manifest sync service. The catalog service is named with
// a "Catalog" suffix to keep both addressable.
//
// Slice scope (B2 is split across multiple slices for size):
//
//   B2a (this file): Create, Get, List, AddMount, AddEnv, AddPort,
//   SetImage, SetTarget — the "happy path" RPCs the user-host CLI
//   needs to assemble a workspace.
//
//   B2b: RemoveMount, RemapMount, FlagMount, RemoveEnv, RemovePort.
//   B2c: Validate, Launch, Stop (workspace → SandboxSpec dispatch).
//   B2d: Lock, Unlock, Adopt.
//
// Authorization model: every RPC is authenticated via mTLS peer
// fingerprint (extracted by withPeerMiddleware). For B2a, any
// authenticated caller can mutate any workspace — the per-owner
// lock subsystem that scopes mutation to the holder lands in B2d.
// owner_fingerprint on Workspace is informational and scopes
// name-based handle resolution (your "myapp" can't collide with
// someone else's "myapp").

